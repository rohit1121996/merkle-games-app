export const formatDate = (dates: string): string => {
  if (!dates) return "";
  const date = new Date(dates);
  if (Number.isNaN(date.getTime())) return "";
  return new Intl.DateTimeFormat("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
    timeZone: "UTC",
  }).format(date);
};
